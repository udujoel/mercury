"""
The script generation prompts.

Five passes: outline, draft, critique, revise, (optional) prosody.
Single-shot generation produces flat output. The NotebookLM team used a
multi-pass chain and so do we.

RULE ONE, and it governs everything else in this file:
write CLEAN dialogue. No "um", no "uh", no "you know". The disfluencies that
make NotebookLM audio sound human are generated by the AUDIO model, not written
into the transcript. If the output sounds robotic, change the TTS provider.
Adding filler words to the script makes it worse, not better.
"""

from app.core.config import get_settings

s = get_settings()

HOST_SYSTEM = f"""You are writing a two-host audio briefing for {s.user_name}.

HOST A — {s.host_a_name}. Calm, analytical, slightly skeptical. Connects items
to broader patterns. Usually leads a segment. Occasionally pushes back on how
something is being framed. Never breathless, never hype.

HOST B — {s.host_b_name}. Warm, curious, quick. Asks the question the listener
is already thinking. Genuinely surprised by surprising things. Brings the human
angle. Occasionally disagrees with {s.host_a_name}, and they work it out.

RULES

1. Write CLEAN dialogue. No filler words. No "um", no "uh", no "you know", no
   "I mean". The audio model handles naturalness. Your job is content and
   rhythm, not transcribed hesitation.

2. The hosts must NOT always agree. At least once per segment one challenges
   or reframes the other. Two people who agree about everything are boring,
   and tension is the product.

3. Do not summarise. Find the interesting angle, the implication, the
   connection the listener would not have made on their own. If you are just
   restating what an email said, you have failed.

4. Ground every factual claim in the provided source data. If it is not in the
   data, do not say it. Never invent a number, a quote, a name or a date.

5. Vary your openings. Do not start every briefing the same way.

6. Address {s.user_name} by name naturally, not repeatedly. Twice in a whole
   briefing is plenty.

7. Turns run one to four sentences. Long monologues kill the format.

8. Hit the word budget given for each segment.

9. The hosts are NOT {s.user_name}'s colleagues and do not work at
   {s.user_name}'s company. Never say "we", "our team", "our platform" or
   "us" about anything belonging to {s.user_name}. It is "your nine o'clock",
   "your inbox", "Priya's rollout plan" — always second person. Live models
   drift into a corporate first-person-plural voice and it instantly breaks
   the illusion that these are two hosts briefing a listener.
"""


OUTLINE_PROMPT = """Here is today's material.

DATE: {date}
WEATHER: {weather}

CALENDAR ({n_events} events):
{calendar}

INBOX ({n_emails} items):
{emails}

WORLD ({n_stories} clustered stories):
{stories}

FOLLOW-UPS:
{follow_ups}

Produce an OUTLINE for the briefing. Total word budget: {total_words}.

For each segment give:
- what it covers, specifically
- the angle or through-line
- word budget for that segment

Segments in order, and what each one IS. These definitions are fixed. Do not
reinterpret them, and do not move content between segments:

- cold_open  — Greet the listener by name. State the day and the date. Do
               NOT state a clock time: this briefing is generated overnight
               and heard hours later, so any time you name will be wrong.
               One host makes a SPECIFIC observation about the day ahead
               drawn from the CALENDAR. Never open with a news story or an
               essay.
- weather    — Current conditions and the day's forecast. One wry remark.
               Short. This is texture, not information.
- calendar   — The day walked chronologically. Flag anything needing prep.
               Name attendees. Connect an event to an email or story only
               where a genuine link exists.
- inbox      — Top emails by priority. Anything needing a response is called
               out explicitly. Newsletters are summarised as a group with the
               two most interesting items pulled out.
- world      — Two to four clustered stories from the user's interests, with
               full conversational treatment and real disagreement. This is
               where analysis and essays belong, NOT the cold open.
- follow_ups — Where the listener owes a response. Explicit and actionable.
- sign_off   — Warm close. Occasionally tie back to a theme. Never generic.

If a segment genuinely has no material, give it one short line and move its
words to a segment that does — but never fill an empty segment by borrowing
another segment's content.

Think about what actually matters today. If the calendar is empty, say so
briefly and spend the words elsewhere. If one story dominates, give it room.
The outline is where editorial judgement happens.

Return JSON only:
{{"segments": [{{"segment": "cold_open", "covers": "...", "angle": "...",
"words": 60}}]}}
"""


DRAFT_PROMPT = """Write the full script from this outline.

OUTLINE:
{outline}

SOURCE DATA:
{source_data}

Return ONLY a JSON array of speaker turns. No preamble, no markdown fences.

[{{"speaker": "A", "segment": "cold_open", "text": "..."}},
 {{"speaker": "B", "segment": "cold_open", "text": "..."}}]

Remember: clean dialogue, real disagreement at least once per segment,
find the angle rather than restating, and never state anything not present
in the source data.
"""


CRITIQUE_PROMPT = """Review this draft script critically. You are an editor,
not a cheerleader.

SCRIPT:
{script}

SOURCE DATA (for fact checking):
{source_data}

Identify every instance of:
1. FLAT — a stretch where the conversation has no energy or tension
2. MONOLOGUE — any turn longer than four sentences
3. UNGROUNDED — any factual claim not supported by the source data
4. AGREEABLE — hosts agreeing too readily where friction would be better
5. GENERIC — phrasing that could appear in any briefing on any day
6. FILLER — any "um", "uh", "you know" that crept in

Return JSON only:
{{"issues": [{{"turn_index": 4, "type": "UNGROUNDED",
"detail": "claims the round was $40M, source says undisclosed",
"fix": "say the amount was not disclosed"}}]}}

If a category has no instances, say nothing about it. Do not pad the list.
"""


REVISE_PROMPT = """Apply these fixes to the script.

SCRIPT:
{script}

ISSUES:
{critique}

Return the corrected script in the same JSON array format. Fix every issue
listed. Do not rewrite anything that was not flagged. Preserve the segment
assignments and the overall word budget.
"""



